"""Render the wiring and debounce schematics for the chumicro-buttons guide.

Five SVGs land in ``libraries/buttons/docs/schematics/``:

* ``wiring-active-low.svg`` — a momentary switch to GND with the pin's own
  pull-up, which is what ``active_low=True`` (the default) expects.
* ``wiring-active-high.svg`` — a switch to 3V3 with an external pull-down,
  which is what ``active_low=False`` expects.
* ``debounce-rc.svg`` — the RC low-pass on its own, including the series
  resistor that keeps the discharge path finite.
* ``debounce-rc-schmitt.svg`` — an RC network through a 74HC14, which is the
  first arrangement clean enough for ``settle_ms=0``.
* ``debounce-spdt-latch.svg`` — an SPDT switch and a 74HC00 RS latch, the
  arrangement with no bounce to filter at all.

Run::

    python scripts/render_button_schematics.py            # all five
    python scripts/render_button_schematics.py --figure debounce-rc

``schemdraw`` is a host-only documentation tool.  It belongs in the
workspace virtualenv (``uv pip install schemdraw``) and in no library's
``pyproject.toml``: nothing it produces ships to a device.  Preflight does
not run this script for that reason, so re-run it by hand after editing a
figure and commit the SVG alongside the change.

Colors: one mid-tone slate ink for every stroke and every label.  The
documentation site renders these on a dark background and GitHub renders
them on a light one, and an ``<img>`` inherits neither page's colors, so
the ink has to carry about 4:1 contrast against both ends.
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

import schemdraw
from schemdraw import elements as elm
from schemdraw import logic

REPO_ROOT = Path(__file__).resolve().parent.parent
# docs/img/ is regenerated by the docs build from support/docs/, so hand-authored
# figures live in a sibling directory that git actually tracks.
OUT_DIR = REPO_ROOT / "libraries" / "buttons" / "docs" / "schematics"

#: Mid-tone slate: ~3.5:1 on white, ~4.6:1 on the Material slate background.
INK = "#7f8a96"

UNIT = 2.0
LINE_WIDTH = 1.7
LABEL_SIZE = 13
NOTE_SIZE = 11
NOTE_STEP = 0.52

# ---------------------------------------------------------------------------
# The RC numbers
#
# Both RC figures hang the same pull-up and the same capacitor off 3V3 and
# differ only in the series resistor, because the two figures load the RC
# node with different things.  Kilohms times microfarads land in
# milliseconds, so every time constant below is a product of the values as
# they are printed on the drawing.
# ---------------------------------------------------------------------------

SUPPLY_VOLTS = 3.3

#: Pull-up on both RC figures.  Ten kilohms holds the released node at 3V3
#: against pin leakage while costing 330 µA when the button is down.
RC_PULL_UP_KOHM = 10.0

#: Capacitor on both RC figures.  A microfarad-class part is what puts the
#: press edge in the same range as contact bounce; the nanofarad values the
#: tutorials print leave that edge unfiltered.
RC_CAPACITOR_UF = 2.2

#: Series resistor for the bare-pin figure.  It divides against whatever
#: pull-up holds the node up, and a pin's own pull-up can be as low as
#: ``WEAKEST_INTERNAL_PULL_UP_KOHM``, so it has to stay small.
RC_SERIES_PLAIN_KOHM = 2.2

#: Series resistor for the 74HC14 figure.  A logic input has no pull-up to
#: divide against, so this one is free to move up toward R1, which narrows
#: the gap between the two time constants and gentles the contacts.
RC_SERIES_SCHMITT_KOHM = 4.7

#: Weakest internal pull-up a CircuitPython board is likely to hand you.
#: The nRF52840 sits near 13 kΩ; an RP2040 is nearer 50 kΩ, which is kinder.
#: The library turns a pull on for every button, so the low end is what a
#: series resistor has to survive.
WEAKEST_INTERNAL_PULL_UP_KOHM = 13.0

#: Highest voltage a 3.3 V logic input is still guaranteed to read as low,
#: which is the usual 0.3 × VDD.
LOGIC_LOW_CEILING_VOLTS = 0.3 * SUPPLY_VOLTS

#: 74HC14 switching points at 3.3 V, interpolated from the typical curves in
#: the Nexperia datasheet.  A rising input has to pass the upper one before
#: the output flips low; a falling input has to pass the lower one before it
#: flips back.  The gap between them is the hysteresis the figure relies on.
SCHMITT_UPPER_VOLTS = 1.8
SCHMITT_LOWER_VOLTS = 1.05


def _drawing() -> schemdraw.Drawing:
    """Return an empty drawing carrying the house style."""
    schemdraw.use("svg")
    drawing = schemdraw.Drawing()
    drawing.config(
        unit=UNIT,
        fontsize=LABEL_SIZE,
        font="Arial",
        color=INK,
        lw=LINE_WIDTH,
        # Elements that fill a shape with "the background" -- switch
        # contacts, open terminals -- resolve it to this.  Leaving it
        # transparent keeps them hollow on a light page and a dark one.
        bgcolor="none",
    )
    return drawing


def _text(
    drawing: schemdraw.Drawing,
    xy: tuple[float, float],
    text: str,
    *,
    halign: str = "left",
    valign: str = "center",
    size: float = NOTE_SIZE,
) -> None:
    """Place one line of free text at *xy*."""
    drawing.add(
        elm.Label().at(xy).label(text, halign=halign, valign=valign, fontsize=size)
    )


def _notes(
    drawing: schemdraw.Drawing,
    xy: tuple[float, float],
    lines: list[str],
    *,
    size: float = NOTE_SIZE,
    step: float = NOTE_STEP,
) -> None:
    """Place a left-aligned block of notes, one drawn label per line.

    schemdraw centers the continuation lines of a multi-line label, so a
    block that has to align on its left edge is drawn a line at a time.
    """
    left, top = xy
    for index, line in enumerate(lines):
        _text(drawing, (left, top - index * step), line, halign="left", valign="top", size=size)


def _gpio_terminal(
    drawing: schemdraw.Drawing,
    xy: tuple[float, float],
    text: str = "GPIO",
) -> None:
    """Mark where the wire meets the microcontroller pin."""
    drawing.add(elm.Dot(open=True).at(xy))
    _text(drawing, (xy[0] + 0.2, xy[1] + 0.18), text, halign="left", valign="bottom", size=LABEL_SIZE)


