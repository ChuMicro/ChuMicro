def main(argv: list[str] | None = None) -> int:
    """Render every figure, or the one named by ``--figure``."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--figure",
        choices=sorted(FIGURES),
        help="render one figure instead of all five",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=OUT_DIR,
        help=f"destination directory (default: {OUT_DIR.relative_to(REPO_ROOT)})",
    )
    args = parser.parse_args(argv)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    names = [args.figure] if args.figure else sorted(FIGURES)
    for name in names:
        target = args.out_dir / f"{name}.svg"
        FIGURES[name](target)
        print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
