def wiring_active_low(path: Path) -> None:
    """Momentary switch to GND, pull-up supplied by the pin itself."""
    drawing = _drawing()

    # The pull-up and the rail it hangs off are drawn dashed because they
    # are already inside the chip -- there is no part to buy here.
    drawing.add(elm.Vdd().at((0, 5.6)).label("3V3").linestyle("--"))
    drawing.add(
        elm.Resistor()
        .at((0, 5.6))
        .to((0, 3.8))
        .linestyle("--")
        .label("internal pull-up\n(tens of kΩ)", loc="top")
    )
    # .right() resets the direction the resistor left behind: a Rect drawn
    # with the pen still pointing down comes out rotated a quarter turn.
    drawing.add(elm.Rect(corner1=(-3.3, 3.0), corner2=(1.7, 6.6), ls="--").at((0, 0)).right())
    _text(drawing, (-0.8, 2.75), "inside the microcontroller", halign="center", valign="top")

    drawing.add(elm.Line().at((0, 3.8)).to((4.6, 3.8)))
    _text(drawing, (1.95, 3.98), "GPIO", halign="left", valign="bottom", size=LABEL_SIZE)

    drawing.add(elm.Button().at((4.6, 3.8)).to((4.6, 2.3)).label("SW1\nmomentary", loc="bot"))
    drawing.add(elm.Line().at((4.6, 2.3)).to((4.6, 1.8)))
    drawing.add(elm.Ground().at((4.6, 1.8)))

    _notes(
        drawing,
        (-3.3, 0.35),
        [
            "Released: the pull-up holds the pin at 3V3, so the pin reads HIGH.",
            "Pressed: the switch ties the pin to 0 V, so the pin reads LOW.",
            "This is Button(pin, active_low=True), the default. Add no resistor.",
            "Bare contacts bounce: leave settle_ms at 20.",
        ],
    )
    drawing.save(str(path), transparent=True)


